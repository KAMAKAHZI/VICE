CREATE OR REPLACE FUNCTION public.get_or_create_holder()
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare p public.profiles%rowtype; h public.holders%rowtype; cid text; hid uuid; x int;
begin
 if auth.uid() is null then raise exception 'Sign in required'; end if;
 perform pg_catalog.pg_advisory_xact_lock(793151205);
 select * into p from public.profiles where id=auth.uid();
 if not found then raise exception 'Invite is required'; end if;
 select * into h from public.holders where profile_id=p.id;
 if found then return to_jsonb(h); end if;
 -- Appointed holders may exist before their invite is accepted. Link that record
 -- rather than allocating a second client ID against the 250-holder cap.
 select * into h from public.holders where profile_id is null and email=p.email order by created_at limit 1 for update;
 if found then
  update public.holders set profile_id=p.id, user_id=p.id where id=h.id returning * into h;
  update public.profiles set client_id=h.client_id where id=p.id;
  return to_jsonb(h);
 end if;
 select count(*) into x from public.holders where coalesce(status,'ACTIVE')<>'ESTATE_RESERVE';
 if x>=250 then raise exception '250-holder issuer capacity reached'; end if;
 cid := 'VC-' || lpad(nextval('public.vice_client_seq')::text,6,'0');
 hid := p.id;
 insert into public.holders(id,user_id,client_id,profile_id,name,email,status,vice_units,v4x_units) values
 (hid,p.id,cid,p.id,p.name,p.email,'ACTIVE',0,0) returning * into h;
 update public.profiles set client_id=cid where id=p.id;
 insert into public.iru_events(event_type,payload,actor_id,actor_role)
 values ('HOLDER_ADDED',jsonb_build_object('type','HOLDER_ADDED','holderId',hid::text,
 'name',p.name,'email',p.email,'holderType','Standard','at',now()::text,'by','verified-signup'),
 p.id,p.role);
 return to_jsonb(h);
end $function$
;

CREATE OR REPLACE FUNCTION public.append_iru_event(p_payload jsonb, p_correlation_id uuid DEFAULT gen_random_uuid())
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare et text; pid text; hid uuid; qty bigint; r public.holders%rowtype; before_ct int; after_ct bigint; seq_id bigint;
begin
 if auth.uid() is null or not public.is_super() then raise exception 'IRU mutation requires SUPER_ADMIN'; end if;
 if p_payload is null or jsonb_typeof(p_payload)<>'object' then raise exception 'Invalid event'; end if;
 et:=p_payload->>'type';
 if et is null or et not in ('HOLDER_ADDED','HOLDER_UPDATED','HOLDER_FROZEN','HOLDER_UNFROZEN',
 'UNITS_ISSUED','UNITS_RETIRED','ALLOCATION_CREATED','ALLOCATION_APPROVED','ALLOCATION_RESERVED','ALLOCATION_DISTRIBUTED',
 'ALLOCATION_REVOKED','ALLOCATION_FROZEN','ALLOCATION_UNFROZEN','VALUATION_PROPOSED','VALUATION_APPROVED',
 'VALUATION_REJECTED','LEGAL_STATUS_RECORDED','ENTRY_CLASS_RECORDED','TIER_ASSIGNED','LEGACY_RECORDED')
 then raise exception 'Unknown IRU event'; end if;
 if length(p_payload::text)>16000 then raise exception 'Event payload exceeds 16KB'; end if;
 perform pg_catalog.pg_advisory_xact_lock(793151205); -- serializes holders + supply
 if et='HOLDER_ADDED' then
   hid:=(p_payload->>'holderId')::uuid;
   if nullif(trim(p_payload->>'name'),'') is null then raise exception 'Holder name required'; end if;
   select count(*) into before_ct from public.holders where coalesce(status,'ACTIVE')<>'ESTATE_RESERVE';
   if before_ct >= 250 then raise exception '250-holder cap exceeded'; end if;
   -- Appointed holders are NOT automatically linked to the issuer's own auth user.
   IF EXISTS (
       SELECT 1 FROM information_schema.columns
       WHERE table_schema='public' AND table_name='holders' AND column_name='user_id'
         AND is_nullable='NO' AND column_default IS NULL
   ) THEN RAISE EXCEPTION 'Legacy holders.user_id is NOT NULL: cannot appoint an unlinked holder safely. Request holder migration.'; END IF;
   insert into public.holders(id,client_id,name,email,holder_type,wallet,status,vice_units,v4x_units)
   values(hid,'VC-'||lpad(nextval('public.vice_client_seq')::text,6,'0'),
   left(p_payload->>'name',256),nullif(p_payload->>'email',''),
   coalesce(p_payload->>'holderType','Standard'),p_payload->>'wallet','ACTIVE',0,0);
 elsif et in ('UNITS_ISSUED','UNITS_RETIRED') then
   pid:=p_payload->>'program';
   if pid not in ('VICE','V4X') then raise exception 'Unknown program'; end if;
   hid:=(p_payload->>'holderId')::uuid;
   select * into r from public.holders where id=hid for update;
   if not found then raise exception 'Holder not found'; end if;
   if coalesce(p_payload->>'units','') !~ '^[0-9]{1,12}$' then raise exception 'Whole units required'; end if;
   qty:=(p_payload->>'units')::bigint;
   if qty<=0 then raise exception 'Positive units required'; end if;
   if et='UNITS_ISSUED' then
     update public.iru_program_counters set issued=issued+qty,updated_at=now()
       where program=pid and issued+qty<=2500000 returning issued into after_ct;
     if not found then raise exception 'Strategic holder pool exhausted'; end if;
     if pid='VICE' then update public.holders set vice_units=vice_units+qty where id=hid;
     else update public.holders set v4x_units=v4x_units+qty where id=hid; end if;
   else
     if (pid='VICE' and r.vice_units<qty) or (pid='V4X' and r.v4x_units<qty) then
       raise exception 'Retirement exceeds holdings'; end if;
     update public.iru_program_counters set issued=issued-qty,retired=retired+qty,updated_at=now() where program=pid;
     if pid='VICE' then update public.holders set vice_units=vice_units-qty where id=hid;
     else update public.holders set v4x_units=v4x_units-qty where id=hid; end if;
   end if;
 elsif et='TIER_ASSIGNED' then
   update public.holders set tier=p_payload->>'tier' where id=(p_payload->>'holderId')::uuid;
   IF NOT FOUND THEN RAISE EXCEPTION 'Holder not found'; END IF;
 elsif et='LEGACY_RECORDED' then
   update public.holders set legacy=p_payload->>'order' where id=(p_payload->>'holderId')::uuid;
   IF NOT FOUND THEN RAISE EXCEPTION 'Holder not found'; END IF;
 end if;
 insert into public.iru_events(event_type,payload,actor_id,actor_role,correlation_id)
 values(et,p_payload,auth.uid(),'SUPER_ADMIN',p_correlation_id) returning seq into seq_id;
 return jsonb_build_object('seq',seq_id,'event_type',et,'correlation_id',p_correlation_id);
end $function$
;

