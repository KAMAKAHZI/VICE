CREATE OR REPLACE FUNCTION public.advance_iru_allocation(p_allocation_id uuid, p_action text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
    a public.allocations%ROWTYPE;
    v_issued numeric;
    v_reserved numeric;
BEGIN
    IF auth.uid() IS NULL OR NOT public.is_super() THEN
        RAISE EXCEPTION 'SUPER_ADMIN authorization required';
    END IF;

    IF p_action IS NULL
       OR p_action NOT IN ('APPROVE', 'RESERVE') THEN
        RAISE EXCEPTION 'Unsupported allocation action';
    END IF;

    PERFORM pg_catalog.pg_advisory_xact_lock(793151205);

    SELECT *
    INTO a
    FROM public.allocations
    WHERE id = p_allocation_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Allocation not found';
    END IF;

    IF p_action = 'APPROVE' THEN

        IF a.status <> 'PENDING' THEN
            RAISE EXCEPTION
                'Only PENDING allocations may be approved';
        END IF;

        UPDATE public.allocations
        SET status = 'APPROVED',
            approved_by = auth.uid(),
            approved_at = now()
        WHERE id = a.id;

    ELSIF p_action = 'RESERVE' THEN

        IF a.status <> 'APPROVED' THEN
            RAISE EXCEPTION
                'Only APPROVED allocations may be reserved';
        END IF;

        SELECT issued
        INTO v_issued
        FROM public.iru_program_counters
        WHERE program = a.class
        FOR UPDATE;

        IF NOT FOUND THEN
            RAISE EXCEPTION 'Missing IRU supply counter';
        END IF;

        SELECT COALESCE(SUM(units), 0)
        INTO v_reserved
        FROM public.allocations
        WHERE class = a.class
          AND status = 'RESERVED';

        IF v_issued + v_reserved + a.units > 2500000 THEN
            RAISE EXCEPTION
                'Strategic-holder program capacity exceeded';
        END IF;

        UPDATE public.allocations
        SET status = 'RESERVED',
            reserved_at = now()
        WHERE id = a.id;

    END IF;

    RETURN pg_catalog.jsonb_build_object(
        'allocation_id', a.id,
        'action', p_action,
        'status',
            CASE
                WHEN p_action = 'APPROVE'
                    THEN 'APPROVED'
                ELSE 'RESERVED'
            END
    );
END;
$function$
;

CREATE OR REPLACE FUNCTION public.guard_iru_reserved_capacity()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
DECLARE
    v_reserved numeric;
BEGIN
    IF NEW.program NOT IN ('VICE', 'V4X') THEN
        RAISE EXCEPTION 'Invalid IRU program';
    END IF;

    SELECT COALESCE(SUM(a.units), 0)
    INTO v_reserved
    FROM public.allocations a
    WHERE a.class = NEW.program
      AND a.status = 'RESERVED';

