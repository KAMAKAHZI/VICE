CREATE OR REPLACE FUNCTION public.validate_invite(p_code text, p_email text)
 RETURNS jsonb
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare v public.invites%rowtype;
begin
 if length(coalesce(p_code,'')) > 128 then return jsonb_build_object('valid',false); end if;
 select * into v from public.invites where code=p_code and not used and not revoked
  and (expires_at is null or expires_at>now());
 if not found or v.email is null or lower(v.email::text) is distinct from lower(p_email) then
  return jsonb_build_object('valid',false);
 end if;
 return jsonb_build_object('valid',true,'name',v.for_user); -- never publish staff role or VIP
end $function$
;

CREATE OR REPLACE FUNCTION public.redeem_invite(p_code text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
    v public.invites%rowtype;
    u record;
    p public.profiles%rowtype;
BEGIN
    IF auth.uid() IS NULL THEN
        RAISE EXCEPTION 'Sign in required'
            USING errcode = '28000';
    END IF;

    SELECT id, email, email_confirmed_at,
           raw_user_meta_data
    INTO u
    FROM auth.users
    WHERE id = auth.uid();

    IF u.email_confirmed_at IS NULL THEN
        RAISE EXCEPTION
            'Verify your email before redeeming the invite';
    END IF;

    IF length(coalesce(p_code, '')) NOT BETWEEN 5 AND 128 THEN
        RAISE EXCEPTION 'Invalid invite';
    END IF;

    SELECT *
    INTO v
    FROM public.invites
    WHERE code = p_code
      AND NOT used
      AND NOT revoked
      AND (expires_at IS NULL OR expires_at > now())
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Invite expired or already redeemed';
    END IF;

    IF v.email IS NULL
       OR lower(v.email::text)
          IS DISTINCT FROM lower(u.email::text) THEN
        RAISE EXCEPTION
            'Invite requires an email matching authenticated identity';
    END IF;

    -- Existing profiles cannot be promoted or demoted
    -- by redeeming another invitation.
    SELECT *
    INTO p
    FROM public.profiles
    WHERE id = u.id
    FOR UPDATE;

    IF FOUND THEN
        RAISE EXCEPTION
            'Profile already exists; contact an administrator';
    END IF;

    INSERT INTO public.profiles (
        id, email, name, role,
        vip_access, avatar_initials
    )
    VALUES (
        u.id,
        u.email,
        coalesce(
            nullif(v.for_user, ''),
            nullif(u.raw_user_meta_data->>'name', ''),
            split_part(u.email, '@', 1)
        ),
        v.role,
        v.vip_access,
        upper(left(
            coalesce(
                v.for_user,
                split_part(u.email, '@', 1)
            ), 2
        ))
    )
    RETURNING * INTO p;

    UPDATE public.invites
    SET used = true,
        used_by = u.id,
        used_at = now()
    WHERE id = v.id;

    RETURN jsonb_build_object(
        'id', p.id,
        'role', p.role,
        'name', p.name,
        'vip_access', p.vip_access
    );
END;
$function$
;

