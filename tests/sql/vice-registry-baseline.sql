       OR NEW.issued < 0
       OR NEW.issued + v_reserved > 2500000 THEN

        RAISE EXCEPTION
          'VICE OS: % supply exceeds available capacity after reservations',
          NEW.program;
    END IF;

    RETURN NEW;
END;
$function$
