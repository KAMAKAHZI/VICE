CREATE OR REPLACE FUNCTION public.lookup_email_for_login(p_identifier text)
 RETURNS text
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE v_email text;
BEGIN
 IF length(coalesce(p_identifier,'')) NOT BETWEEN 3 AND 100
    OR position('@' IN coalesce(p_identifier,''))>0 THEN RETURN NULL; END IF;
 SELECT lower(p.email) INTO v_email FROM public.profiles p
 WHERE lower(p.username)=lower(trim(p_identifier))
 LIMIT 1;
 RETURN v_email;
END $function$
;

CREATE OR REPLACE FUNCTION public.verify_certificate(p_cert_id text)
 RETURNS jsonb
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  rec record;
  result jsonb;
begin
  select * into rec from public.certificates
    where cert_id = upper(trim(p_cert_id)) limit 1;

  if not found then
    return jsonb_build_object('valid', false, 'reason', 'NOT_FOUND');
  end if;

  if rec.revoked then
    return jsonb_build_object(
      'valid', false,
      'reason', 'REVOKED',
      'revoked_at', rec.revoked_at,
      'revoked_reason', rec.revoked_reason
    );
  end if;

  return jsonb_build_object(
    'valid', true,
    'cert_id', rec.cert_id,
    'name', rec.holder_name,
    'course', rec.course_title,
    'issued_at', rec.issued_at,
    'expires_at', rec.expires_at,
    'scores', rec.scores,
    'overall_score', rec.overall_score,
    'digest', rec.digest
  );
end;
$function$
