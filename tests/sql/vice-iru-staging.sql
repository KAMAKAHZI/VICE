-- Match the existing certificate trigger's authorization boundary. A reversal
-- must not impersonate an authenticated issuer or generate a new certificate.
CREATE FUNCTION public.fixture_certificate_guard() RETURNS trigger LANGUAGE plpgsql AS $$BEGIN
 IF NEW.event_type IN ('UNITS_ISSUED','UNITS_RETIRED') AND
  (auth.uid() IS NULL OR NOT public.is_super() OR NEW.actor_id IS DISTINCT FROM auth.uid())
 THEN RAISE EXCEPTION 'Certified unit event requires issuer authorization';END IF;
 RETURN NEW;END$$;
CREATE TRIGGER fixture_certificate_guard AFTER INSERT ON public.iru_events FOR EACH ROW EXECUTE FUNCTION public.fixture_certificate_guard();
