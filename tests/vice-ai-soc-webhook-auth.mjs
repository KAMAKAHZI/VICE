import assert from 'node:assert/strict';
import {createHmac} from 'node:crypto';
import {verifySocWebhook,authenticateSocWebhook} from '../security/ai-soc/webhook-auth.mjs';
const now=Date.parse('2026-10-25T12:00:00Z');
const secret='a-secure-test-only-secret-that-is-long-enough';
const timestamp=String(now);
const nonce='nonce_12345678901234567890';
const rawBody=JSON.stringify({type:'MFA_REPLAY',actorId:'actor-1'});
const signature='sha256='+createHmac('sha256',secret).update(timestamp+'.'+nonce+'.'+rawBody).digest('hex');
const valid={rawBody,timestamp,nonce,signature,secret,now};
assert.equal(verifySocWebhook(valid),true);
assert.equal(verifySocWebhook({...valid,rawBody:rawBody+' '}),false);
assert.equal(verifySocWebhook({...valid,signature:signature.slice(0,-1)+'x'}),false);
assert.equal(verifySocWebhook({...valid,now:now+300001}),false);
assert.equal(verifySocWebhook({...valid,secret:'weak'}),false);
assert.equal(verifySocWebhook({...valid,rawBody:'x'.repeat(65537)}),false);
const used=new Set();
const consume=async n=>{if(used.has(n))return false;used.add(n);return true};
assert.equal((await authenticateSocWebhook(valid,consume)).serverAuthenticated,true);
await assert.rejects(()=>authenticateSocWebhook(valid,consume),/Replay detected/);
await assert.rejects(()=>authenticateSocWebhook(valid,async()=>{throw new Error('store offline')}),/store offline/);
console.log('PASS SOC webhook signature, tamper, expiry and replay contracts (offline only)');
